// node tools/body/correctives/make-data.mjs <dumpDir> <target.bin>
// Turns the target shape made in Blender into the corrective offset of the rest skin, and writes
// apps/web/src/components/body/shoulder-correctives-data.ts.
// dumpDir holds what dump.test.ts wrote: final.bin (the skin as drawn, world), inv.bin (each
// point's skinning undone), trunk.json (the trunk bone's move), meta.json.
import fs from "node:fs";
import path from "node:path";

const [dir, targetFile] = process.argv.slice(2);
const meta = JSON.parse(fs.readFileSync(path.join(dir, "meta.json"), "utf8"));
const f32 = (f) => { const b = fs.readFileSync(f); return new Float32Array(b.buffer, b.byteOffset, b.byteLength / 4); };
const final = f32(path.join(dir, "final.bin"));
const target = f32(targetFile);
const inv = f32(path.join(dir, "inv.bin")); // each point's skinning undone, 3x3 column-major
// The turn of a skinning matrix (columns c0, c1, c2): c0 made unit, c1 square to it, c2 their cross.
// The shader and shoulder-correctives.ts take it the same way.
export function turnOf(m) {
  const c0 = [m[0], m[1], m[2]], c1 = [m[3], m[4], m[5]];
  const n0 = Math.hypot(...c0); const a = c0.map((v) => v / n0);
  const d = c1[0] * a[0] + c1[1] * a[1] + c1[2] * a[2];
  const b0 = c1.map((v, k) => v - d * a[k]); const n1 = Math.hypot(...b0); const b = b0.map((v) => v / n1);
  return [a, b, [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]];
}
function invert3(e) {
  const [a, b, c, d, f, g, h, i, j] = e; // column-major: col0 = a b c
  const A = f * j - g * i, B = -(d * j - g * h), C = d * i - f * h;
  const det = a * A + b * B + c * C;
  return [A / det, -(b * j - c * i) / det, (b * g - c * f) / det, B / det, (a * j - c * h) / det, -(a * g - c * d) / det, C / det, -(a * i - b * h) / det, (a * f - b * d) / det];
}
const t = JSON.parse(fs.readFileSync(path.join(dir, "trunk.json"), "utf8")); // spine_03's move, column-major 4x4
const SCALE = 10000; // offsets kept as tenths of a millimetre
const rows = [];
let most = 0;
for (let i = 0; i < meta.n; i++) {
  const d = [0, 1, 2].map((k) => target[i * 3 + k] - final[i * 3 + k]);
  if (Math.hypot(...d) < 1e-4) continue;
  // Back into the rest space by the turn of this point's own skinning (its transpose undoes it):
  // the whole skinning inverted magnified the offset up to 3x where it squashes the skin (the
  // armpit), and the trunk's turn alone left the armpit's offset behind when the arm moved.
  const [a, b, c] = turnOf(invert3(inv.subarray(i * 9, i * 9 + 9)));
  const o = [a, b, c].map((col) => col[0] * d[0] + col[1] * d[1] + col[2] * d[2]);
  most = Math.max(most, Math.hypot(...o));
  rows.push([i, ...o.map((v) => Math.round(v * SCALE))]);
}
const buf = Buffer.alloc(rows.length * 10);
rows.forEach(([i, x, y, z], r) => {
  buf.writeUInt32LE(i, r * 10);
  buf.writeInt16LE(x, r * 10 + 4);
  buf.writeInt16LE(y, r * 10 + 6);
  buf.writeInt16LE(z, r * 10 + 8);
});
// The arm's direction at the pose, shoulder to elbow, in the trunk's rest frame: the shape blends in
// as the arm comes near it.
const arm = [0, 1, 2].map((k) => meta.elbowR[k] - meta.shoulderR[k]);
const armDir = [0, 1, 2].map((c) => t[c * 4] * arm[0] + t[c * 4 + 1] * arm[1] + t[c * 4 + 2] * arm[2]);
const dl = Math.hypot(...armDir);
const out = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1")), "../../../apps/web/src/components/body/shoulder-correctives-data.ts");
fs.writeFileSync(out, `// Generated by tools/body/correctives/make-data.mjs. Do not edit by hand.
// The right shoulder's corrective, made with the arm raised ${meta.elevation.toFixed(1)} degrees: the arm's direction
// at that pose in the trunk's rest frame, and per point its index (uint32) and offset added after
// skinning, turned back by that point's own skinning turn (3 x int16, metres x scale), base64.
export const SHOULDER_CORRECTIVE = { arm: [${armDir.map((v) => (v / dl).toFixed(4)).join(", ")}], scale: ${SCALE}, data: "${buf.toString("base64")}" };
`);
console.log("points", rows.length, "largest offset cm", (most * 100).toFixed(2), "->", out);
