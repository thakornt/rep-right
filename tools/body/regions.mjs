// Per-vertex muscle region of the body, from the muscle map (public/models/muscles.png) at each
// vertex's texture coordinate, written to apps/web/src/components/body/body-regions.ts. The
// shoulder skin's bone weights are set from these regions at load (shoulder-weights.ts). Rerun after
// rebuilding body.glb or the muscle map:
//   node tools/body/regions.mjs

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const web = new URL("../../apps/web/", import.meta.url);
const require = createRequire(new URL("package.json", web));
const sharp = require("sharp");
const { GLTFLoader } = await import(new URL("node_modules/three/examples/jsm/loaders/GLTFLoader.js", web));

const buf = readFileSync(new URL("public/models/body.glb", web));
const gltf = await new Promise((ok, no) => new GLTFLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), "", ok, no));
let mesh;
gltf.scene.traverse((o) => { if (!mesh && o.isSkinnedMesh) mesh = o; });
const uv = mesh.geometry.attributes.uv;
const { data, info } = await sharp(new URL("public/models/muscles.png", web).pathname).raw().toBuffer({ resolveWithObject: true });
const out = new Uint8Array(uv.count);
for (let i = 0; i < uv.count; i++) {
  // The map is read with flipY off, so v runs down the image.
  const x = Math.min(info.width - 1, Math.max(0, Math.round(uv.getX(i) * info.width - 0.5)));
  const y = Math.min(info.height - 1, Math.max(0, Math.round(uv.getY(i) * info.height - 0.5)));
  const v = data[(y * info.width + x) * info.channels];
  out[i] = v % 32; // the region; the cloth step is in the upper bits
}
const b64 = Buffer.from(out).toString("base64");
writeFileSync(new URL("src/components/body/body-regions.ts", web), `// Generated by tools/body/regions.mjs: the muscle region of each vertex of body.glb (ids as in
// muscles.ts), base64. Don't edit by hand.

export const BODY_REGIONS = "${b64}";
`);
const counts = {};
for (const r of out) counts[r] = (counts[r] ?? 0) + 1;
console.log(uv.count, "vertices", JSON.stringify(counts));
